/**
 * Builds a self-hosted Font Awesome subset for the icons this site actually uses.
 *
 * Replaces the render-blocking third-party stylesheet
 *   https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.0/css/all.min.css
 * with public/styles/icons.css + subsetted woff2 files in public/fonts/.
 *
 * The markup contract is unchanged: <i class="fas fa-print"> still works.
 *
 * Run: node scripts/build-icon-subset.mjs
 * Requires: npm i -D @fortawesome/fontawesome-free  and  pip3 install fonttools brotli
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const FA = 'node_modules/@fortawesome/fontawesome-free';
const OUT_CSS = 'public/styles/icons.css';
const OUT_FONTS = 'public/fonts';
const PYFTSUBSET = process.env.PYFTSUBSET
  || `${process.env.HOME}/Library/Python/3.7/bin/pyftsubset`;

/* ---------- 1. which icons does the site use? ---------- */
const walk = (d, fn) => {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p, fn); else fn(p);
  }
};
const STYLE = /^(fas|far|fab|fa|fa-solid|fa-regular|fa-brands|fa-classic|fa-sharp)$/;
const UTIL  = /^fa-(2x|3x|4x|5x|lg|sm|xs|xl|2xl|fw|spin|pulse|border|pull-left|pull-right|rotate-\d+|flip-\w+|stack|stack-1x|stack-2x|inverse|beat|fade|shake|bounce|li|ul|spin-pulse|spin-reverse)$/;
const used = new Set();
const styleClasses = new Set();
const collect = (cls) => {
  for (const tok of cls.split(/\s+/)) {
    if (!tok.startsWith('fa')) continue;
    if (STYLE.test(tok)) { styleClasses.add(tok); continue; }
    if (UTIL.test(tok)) continue;
    if (/^fa-[a-z0-9-]+$/.test(tok)) used.add(tok);
  }
};
walk('src', (p) => {
  if (!/\.(astro|json|ts)$/.test(p)) return;
  const s = fs.readFileSync(p, 'utf8');
  for (const m of s.matchAll(/class(?:Name)?\s*=\s*(?:\{`|["'`])([^"'`}]*)/g)) collect(m[1]);
  for (const m of s.matchAll(/<i[^>]*?class=\\?["']([^"'\\]+)/g)) collect(m[1]);
});

/* ---------- 2. resolve each name to a codepoint from all.css ---------- */
const css = fs.readFileSync(`${FA}/css/all.css`, 'utf8');
const codepoints = new Map();          // fa-name -> "f02f"
for (const m of css.matchAll(/\.(fa-[a-z0-9-]+)::?before\s*\{\s*content:\s*"\\([0-9a-f]+)"/gi)) {
  if (!codepoints.has(m[1])) codepoints.set(m[1], m[2].toLowerCase());
}
const resolved = [], unresolved = [];
for (const n of [...used].sort()) {
  (codepoints.has(n) ? resolved : unresolved).push(n);
}
if (unresolved.length) {
  console.error('\n!! icon names with no rule in Font Awesome 6.5.0:');
  unresolved.forEach((n) => console.error('   ', n));
}

/* ---------- 3. subset each woff2 to the used codepoints ---------- */
const cps = [...new Set(resolved.map((n) => codepoints.get(n)))];
const unicodesArg = cps.map((c) => 'U+' + c.toUpperCase()).join(',');
const FAMILIES = [
  { file: 'fa-solid-900',   family: 'Font Awesome 6 Free',   weight: 900 },
  { file: 'fa-regular-400', family: 'Font Awesome 6 Free',   weight: 400 },
  { file: 'fa-brands-400',  family: 'Font Awesome 6 Brands', weight: 400 },
];
fs.mkdirSync(OUT_FONTS, { recursive: true });

// Drop subset files from a previous run so renamed hashes don't accumulate.
for (const old of fs.readdirSync(OUT_FONTS)) {
  if (/^fa-.*\.subset\.([0-9a-f]{8}\.)?woff2$/.test(old)) fs.unlinkSync(path.join(OUT_FONTS, old));
}

const kept = [];
for (const f of FAMILIES) {
  const src = `${FA}/webfonts/${f.file}.ttf`;
  const tmp = path.join(OUT_FONTS, `${f.file}.subset.tmp.woff2`);
  execFileSync(PYFTSUBSET, [
    src, `--unicodes=${unicodesArg}`, '--flavor=woff2',
    '--layout-features=', '--no-hinting', '--desubroutinize',
    `--output-file=${tmp}`,
  ], { stdio: ['ignore', 'ignore', 'inherit'] });

  // Content hash in the filename, so /fonts/ can be cached immutable for a year:
  // regenerating the subset with new icons produces a new URL rather than a
  // stale font with missing glyphs.
  const buf = fs.readFileSync(tmp);
  const hash = createHash('md5').update(buf).digest('hex').slice(0, 8);
  const out = `${f.file}.subset.${hash}.woff2`;
  fs.renameSync(tmp, path.join(OUT_FONTS, out));

  const before = fs.statSync(`${FA}/webfonts/${f.file}.woff2`).size;
  kept.push({ ...f, out, before, after: buf.length });
}

/* ---------- 4. emit icons.css ---------- */
const face = (f) => `@font-face{font-family:'${f.family}';font-style:normal;font-weight:${f.weight};font-display:block;src:url(/fonts/${f.out}) format('woff2')}`;
const rules = resolved.map((n) => `.${n}:before{content:"\\${codepoints.get(n)}"}`).join('');

const out = `/* Generated by scripts/build-icon-subset.mjs — do not edit by hand.
   Font Awesome Free 6.5.0 (CC BY 4.0 / SIL OFL 1.1 / MIT) — https://fontawesome.com
   Subset to the ${resolved.length} icons this site uses. Regenerate after adding new icons. */
${kept.map(face).join('\n')}
.fa,.fas,.fa-solid,.far,.fa-regular,.fab,.fa-brands{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:var(--fa-display,inline-block);font-style:normal;font-variant:normal;line-height:1;text-rendering:auto}
.fa,.fas,.fa-solid{font-family:'Font Awesome 6 Free';font-weight:900}
.far,.fa-regular{font-family:'Font Awesome 6 Free';font-weight:400}
.fab,.fa-brands{font-family:'Font Awesome 6 Brands';font-weight:400}
.fa:before,.fas:before,.fa-solid:before,.far:before,.fa-regular:before,.fab:before,.fa-brands:before{font-family:inherit;font-weight:inherit}
.fa-fw{text-align:center;width:1.25em}
.fa-spin{animation-name:fa-spin;animation-duration:2s;animation-iteration-count:infinite;animation-timing-function:linear}
@keyframes fa-spin{from{transform:rotate(0)}to{transform:rotate(360deg)}}
@media (prefers-reduced-motion:reduce){.fa-spin{animation-delay:-1ms;animation-duration:1ms;animation-iteration-count:1}}
${rules}
`;
fs.mkdirSync(path.dirname(OUT_CSS), { recursive: true });
fs.writeFileSync(OUT_CSS, out);

/* ---------- report ---------- */
console.log('style classes in use :', [...styleClasses].sort().join(' '));
console.log('icons resolved       :', resolved.length, unresolved.length ? `(UNRESOLVED: ${unresolved.length})` : '');
console.log('\nfont subsetting:');
let b = 0, a = 0;
for (const f of kept) { b += f.before; a += f.after;
  console.log(`  ${f.out.padEnd(30)} ${(f.before/1024).toFixed(0).padStart(4)}KB -> ${(f.after/1024).toFixed(1).padStart(5)}KB`); }
console.log(`  ${'TOTAL webfonts'.padEnd(30)} ${(b/1024).toFixed(0).padStart(4)}KB -> ${(a/1024).toFixed(1).padStart(5)}KB`);
const cdnCss = fs.statSync(`${FA}/css/all.min.css`).size;
console.log(`\nCSS: ${(cdnCss/1024).toFixed(0)}KB (cdnjs all.min.css) -> ${(fs.statSync(OUT_CSS).size/1024).toFixed(1)}KB (${OUT_CSS})`);
if (unresolved.length) process.exitCode = 1;
